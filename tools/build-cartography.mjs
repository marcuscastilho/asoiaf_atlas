// Rebuild only from frozen inventory, book evidence and explicit human review.
// Never scans books or runs OCR at render/build time.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const read = (path) => JSON.parse(readFileSync(path, 'utf8'));
const inventory = read('docs/map-features.json');
const evidence = read('docs/map-book-evidence.json');
const contextual = read('docs/map-book-context-overrides.json');
const review = read('docs/map-book-review.json');
const decisions = new Map([...evidence.decisions, ...contextual.decisions].map((entry) => [entry.id, entry]));
const context = {};
vm.createContext(context);
vm.runInContext(readFileSync('assets/js/data.js', 'utf8'), context);
const islands = new Set([
  'Skane', 'Skagos', 'Bear_Island', 'Three_Sisters', 'Sweetsister',
  'Littlesister', 'Longsister', 'Pebble', 'Paps', 'Claw_Isle', 'Fair_Isle',
  'Driftmark', 'Tarth', 'Estermont', 'Arbor', 'Shield_Islands', 'Summer_Islands',
  'Ibben', 'Lorath_(islands)', 'Stepstones', 'Yaros', 'Isle_of_Cedars', 'Ghaen',
  'Basilisk_Isles', 'Isle_of_Toads', 'Isle_of_Tears', 'Naath', 'Iron_Islands',
  'Great_Wyk', 'Old_Wyk', 'Blacktyde', 'Orkmont', 'Harlaw', 'Saltcliffe', 'Pyke_(island)',
]);
const features = inventory.features.map((item) => {
  const decision = decisions.get(item.id);
  const approved = decision && decision.selected &&
    review.approvedLabels[item.id] === decision.label;
  const unchanged = decision && decision.selected && decision.label === item.english;
  const raw = item.key && context.locations[item.key];
  if (item.key && !raw) throw new Error('Unknown original key: ' + item.key);
  if (!(item.x >= 0 && item.x <= inventory.artworkSize &&
        item.y >= 0 && item.y <= inventory.artworkSize)) {
    throw new Error('Out-of-bounds label: ' + item.id);
  }
  return {
    id: item.id,
    ...(item.key ? { key: item.key } : {}),
    english: item.english,
    label: approved ? decision.label : item.english,
    kind: islands.has(item.id) ? 'island' : item.kind,
    x: item.x, y: item.y, fontSize: item.fontSize, angle: item.angle || 0,
    url: (raw && raw.url) || 'https://awoiaf.westeros.org/index.php/' + (item.key || item.id),
    urlProvenance: raw ? 'original-point-url-or-original-key' : 'added-literary-reference-unverified-destination',
    sourceLayer: item.sourceLayer || 'labels.png',
    speculative: !!item.speculative,
    translationStatus: item.key ? 'existing-dictionary' :
      approved ? 'book-context-reviewed' :
      unchanged ? 'original-name-retained' : 'unconfirmed-original-retained',
    bookSource: approved ? decision.selected : null,
  };
});
const rawKeys = new Set(features.filter((item) => item.key).map((item) => item.key));
const newIds = new Set(features.filter((item) => !item.key).map((item) => item.id));
const unresolved = [...new Map(features.filter((item) =>
  item.translationStatus === 'unconfirmed-original-retained').map((item) =>
  [item.id, { id: item.id, english: item.english }])).values()];
const catalog = {
  width: inventory.artworkSize, height: inventory.artworkSize,
  inventoryStatus: 'partial-manual-inventory-not-100-percent',
  labelPositionPrecision: 'approximate-original-artwork-center',
  features,
};
const ascii = (value) => JSON.stringify(value, null, 2).replace(
  /[\u007f-\uffff]/g, (character) =>
    '\\u' + character.charCodeAt(0).toString(16).padStart(4, '0'));
writeFileSync('assets/js/cartography.js',
  '// Generated by tools/build-cartography.mjs from reviewed, frozen evidence.\n' +
  '// Incremental source inventory; not a claim of complete map parity.\n' +
  'window.GOTMAP_CARTOGRAPHY = ' + ascii(catalog) + ';\n');
const coverage = {
  originalInteractivePoints: Object.keys(context.locations).length,
  sourceLabelInstances: features.length,
  originalPointsWithSourceAlignedLabels: rawKeys.size,
  additionalDistinctReferences: newIds.size,
  additionalBookReviewedReferences: new Set(features.filter((item) =>
    !item.key && item.bookSource).map((item) => item.id)).size,
  originalPointsStillUsingFallbackLabels: Object.keys(context.locations).filter((key) => !rawKeys.has(key)),
  unresolvedTranslations: unresolved,
  limitations: [
    'Manual incremental inventory. Raster labels, symbols and their coordinates are not exhaustively audited.',
    'Original point URLs are preserved. Newly supplied literary URLs are inferred and their redirects are not network-verified.',
    'Original solid and hollow artwork symbols are restored over the no-name tiles using the source locations.png and spec_locations.png layers. Additional catalog entries may label geographic areas rather than point symbols.',
    'An unmatched candidate is not evidence that a translation does not exist. Original names are retained until contextual book confirmation.',
  ],
};
writeFileSync('docs/map-coverage.json', ascii(coverage) + '\n');
console.log(JSON.stringify({ ...coverage, originalPointsStillUsingFallbackLabels: coverage.originalPointsStillUsingFallbackLabels.length, unresolvedTranslations: unresolved.length }, null, 2));
